/**
 * Normalizes text by stripping accents, lowercasing, and removing punctuation
 */
export function normalizeText(text: string): string {
  if (!text) return '';
  return text
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '') // strip diacritics / accents
    .replace(/[^a-z0-9\s]/g, '') // keep alphanumeric & spaces
    .trim();
}

/**
 * Perform rich local fuzzy search on catalog
 */
export function filterCatalogByQuery(query: string, genreId?: string): SearchResult[] {
  const normQuery = normalizeText(query);
  const targetGenre = genreId && genreId !== 'all' ? genreId.toLowerCase() : null;

  return POPULAR_KARAOKE_CATALOG.filter((song) => {
    // Check genre match
    if (targetGenre) {
      const matchGenre = song.genre?.some((g) => g.toLowerCase() === targetGenre);
      if (!matchGenre) {
        // Also check keywords if genre is in keywords
        const keywordGenreMatch = song.keywords?.some((k) => normalizeText(k).includes(targetGenre));
        if (!keywordGenreMatch) return false;
      }
    }

    if (!normQuery) return true; // If no text query, return all matching genre items!

    // Text match on title, artist, channel, or keywords
    const normTitle = normalizeText(song.title);
    const normArtist = normalizeText(song.artist);
    const normChannel = normalizeText(song.channelTitle || '');
    const normKeywords = song.keywords?.map((k) => normalizeText(k)) || [];

    const matchesTitle = normTitle.includes(normQuery);
    const matchesArtist = normArtist.includes(normQuery);
    const matchesChannel = normChannel.includes(normQuery);
    const matchesKeywords = normKeywords.some((k) => k.includes(normQuery) || normQuery.includes(k));

    return matchesTitle || matchesArtist || matchesChannel || matchesKeywords;
  });
}
